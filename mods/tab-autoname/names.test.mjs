import assert from "node:assert/strict";
import { branchLabel, folderLabel, isAgentName, tabName, taskLabel } from "./names.js";
const H = "/Users/o";
const shell = { program: { shell: true, name: "zsh" } };
const claude = { program: { agent: true, name: "Claude Code" }, status: "working" };
assert.equal(folderLabel(H, H), "~");
assert.equal(branchLabel("main"), null);
assert.equal(branchLabel("feat/abc-142-checkout-rounding-fix"), "ABC-142");
assert.equal(branchLabel("docs/payment-provider-guide"), "payment-provider…");
assert.equal(taskLabel("✳ Fix login", "/x/api"), "Fix login");
assert.equal(taskLabel("⠂ Claude Code", "/x/api"), null);
assert.equal(taskLabel("~/dev/api", "/x/api"), null);
assert.equal(taskLabel("Fix build for services/api", "/x/api"), "Fix build for services/api");
assert.equal(taskLabel("api", "/x/api"), null);
assert.equal(tabName([{ ...shell, terminal: "t1", cwd: `${H}/repo`, branch: "main" }], H), "repo");
assert.equal(tabName([{ ...claude, terminal: "t1", cwd: `${H}/repo`, branch: "fix/x", title: "✳ Claude Code" }], H), "Claude Code (repo ⎇ fix/x)");
assert.equal(tabName([{ ...shell, terminal: "t1", cwd: `${H}/a` }, { ...claude, terminal: "t2", cwd: `${H}/b`, title: "✳ Fix" }], H), "Fix (b)");
assert.equal(tabName([{ mod: "files", terminal: null }], H), null);
assert.equal(tabName([{ ...shell, terminal: "t1", cwd: `${H}/repo`, branch: "fix/x" }], H), "repo ⎇ fix/x");
assert.equal(isAgentName("Claude Code", []), true);
assert.equal(isAgentName("Kimi Code", [{ program: { agent: true, name: "Kimi Code" } }]), true);
assert.equal(isAgentName("Kimi Code", [shell]), false);
assert.equal(isAgentName("Release prep", [claude]), false);
console.log("ok");
